#include "device.h"
#include "wildfire_lock.h"
#include "s6_app.h"
void main(void)
{
    Device_init();Interrupt_initModule();Interrupt_initVectorTable();
    Wildfire_initBoardLocked();
    gWildfire.initialized=1U;gWildfire.controlQualified=0U;
    S6_appInit();S6_readyStop();
    for(;;)S6_poll();
}
